// v3.1 角色随机姓名（需求：每个角色产生一个随机名字，不要「xxx II / xxx III」这种后缀）
//
// 为什么不继续用罗马数字：
//   旧方案把同名副本渲染成「铁壁镇守 II / III」，在部署页、战报、装备列表里到处都是编号，
//   玩家读到的不是「三个不同的人」，而是「一个人的三份拷贝」——这恰好抵消了 variant.ts
//   花力气做出来的个体差异（属性/体型/性别都不同，名字却在提示他们是同一个）。
//
// 现在每一份副本在生成时（variateHero）拿到一个属于自己的姓名：
//   · 姓来自百家姓，名按性别取字，1~2 字随机（单字名更利落，双字名更饱满）
//   · 完全由种子驱动，同 seed 同名字——不破坏确定性回放
//   · 生成时可传入「已占用姓名」集合做去重，同队不会撞名
//
// 职业称号（HeroDef.name，如「铁壁镇守」）保留，作为姓名旁边的身份标签展示。
