// 中性字：两性通用，只放在第二字位，让姓名不至于全部同质
const NEUTRAL_CHARS = [
  '青', '白', '尘', '舟', '歌', '竹', '秋', '书', '风', '寒',
  '砚', '临', '知', '行', '未', '易', '衡', '和', '安', '常',
];

/** 单次生成（不去重）。抽 1~2 字名：单字 45%，双字 55% */
function rollName(rng: RNG, gender: Gender): string {
  const surname = pick(rng, SURNAMES) ?? '李';
  const pool = gender === 'female' ? FEMALE_CHARS : MALE_CHARS;
  const first = pick(rng, pool) ?? '云';
  if (rng() < 0.45) return surname + first;
  // 第二字从中性池取，避免「岳霆」这种两个重字硬堆在一起的生硬组合
  const second = pick(rng, NEUTRAL_CHARS) ?? '风';
  return surname + first + second;
}

/**
 * 生成一个确定性随机姓名。
 * @param seed   种子（同 seed 必得同名，保证回放一致）
 * @param gender 性别（决定名用字池）
 * @param taken  已被占用的姓名（同队去重；撞名时换盐重摇，最多 64 次后接受重复）
 */
export function randomHeroName(seed: number, gender: Gender, taken: Iterable<string> = []): string {
  const used = new Set(taken);
  let name = '';
  for (let i = 0; i < 64; i++) {
    // 换盐用大素数，避免 seed+1 与相邻角色的种子空间重叠导致连续撞名
    name = rollName(mulberry32((seed + i * 7919) >>> 0), gender);
    if (!used.has(name)) return name;
  }
  return name;
}
